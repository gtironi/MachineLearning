class FocalLoss(nn.Module):
    """Implementação da Focal Loss para segmentação semântica"""
    def __init__(self, alpha=1, gamma=2, reduction='mean'):
        super(FocalLoss, self).__init__()
        self.alpha = alpha
        self.gamma = gamma
        self.reduction = reduction

    def forward(self, inputs, targets):
        ce_loss = F.cross_entropy(inputs, targets, reduction='none')
        pt = torch.exp(-ce_loss)
        focal_loss = self.alpha * (1-pt)**self.gamma * ce_loss

        if self.reduction == 'mean':
            return focal_loss.mean()
        elif self.reduction == 'sum':
            return focal_loss.sum()
        else:
            return focal_loss

class Trainer:
    """Classe para treinar modelos de segmentação semântica"""

    def __init__(self, model, train_loader, val_loader, test_loader, num_classes, device):
        self.model = model
        self.train_loader = train_loader
        self.val_loader = val_loader
        self.test_loader = test_loader
        self.num_classes = num_classes
        self.device = device

        # Histórico de treinamento
        self.train_losses = []
        self.val_losses = []
        self.val_accuracies = []
        self.val_ious = []

    def train_epoch(self, optimizer, criterion, epoch, plot_images=False):
        """Treina por uma época"""
        self.model.train()
        running_loss = 0.0

        pbar = tqdm(self.train_loader, desc=f'Época {epoch+1}')
        for batch_idx, (images, masks) in enumerate(pbar):
            images, masks = images.to(self.device), masks.to(self.device)

            # Zero gradients
            optimizer.zero_grad()

            # Forward pass
            outputs = self.model(images)
            loss = criterion(outputs, masks)

            # Backward pass
            loss.backward()
            optimizer.step()

            running_loss += loss.item()

            # Atualizar barra de progresso
            pbar.set_postfix({'Loss': f'{loss.item():.4f}'})

            # Plotar imagens a cada 5 épocas se solicitado
            if plot_images and epoch % 5 == 0 and batch_idx == 0:
                with torch.no_grad():
                    preds = torch.argmax(outputs, dim=1)
                    plot_predictions(images[0], preds[0].cpu().numpy(), masks[0].cpu().numpy())

        epoch_loss = running_loss / len(self.train_loader)
        return epoch_loss

    def validate(self, criterion):
        """Valida o modelo"""
        self.model.eval()
        running_loss = 0.0

        with torch.no_grad():
            for images, masks in self.val_loader:
                images, masks = images.to(self.device), masks.to(self.device)
                outputs = self.model(images)
                loss = criterion(outputs, masks)
                running_loss += loss.item()

        val_loss = running_loss / len(self.val_loader)

        # Calcular métricas
        val_accuracy = compute_global_accuracy(self.model, self.val_loader)
        val_iou, _ = compute_mean_iou(self.model, self.val_loader, self.num_classes)

        return val_loss, val_accuracy, val_iou

    def train(self, optimizer, criterion, epochs, checkpoint_dir="checkpoints", plot_images=False):
        """Função principal de treinamento"""
        print(f"🚀 Iniciando treinamento por {epochs} épocas...")
        print(f"📊 Modelo: {self.model.__class__.__name__}")
        print(f"🔧 Otimizador: {optimizer.__class__.__name__}")
        print(f"📉 Critério: {criterion.__class__.__name__}")
        print(f"💾 Checkpoints salvos em: {checkpoint_dir}")
        print("-" * 50)

        # Criar diretório de checkpoints
        os.makedirs(checkpoint_dir, exist_ok=True)

        best_val_iou = 0.0
        start_time = time.time()

        for epoch in range(epochs):
            # Treinar
            train_loss = self.train_epoch(optimizer, criterion, epoch, plot_images)

            # Validar
            val_loss, val_accuracy, val_iou = self.validate(criterion)

            # Salvar histórico
            self.train_losses.append(train_loss)
            self.val_losses.append(val_loss)
            self.val_accuracies.append(val_accuracy)
            self.val_ious.append(val_iou)

            # Print do progresso
            print(f"Época {epoch+1:3d}/{epochs} | "
                  f"Train Loss: {train_loss:.4f} | "
                  f"Val Loss: {val_loss:.4f} | "
                  f"Val Acc: {val_accuracy:.4f} | "
                  f"Val IoU: {val_iou:.4f}")

            # Salvar melhor modelo
            if val_iou > best_val_iou:
                best_val_iou = val_iou
                best_model_path = os.path.join(checkpoint_dir, "best_model.pth")
                save_checkpoint(self.model, optimizer, epoch, val_loss, best_model_path)
                print(f"✅ Novo melhor modelo salvo! IoU: {best_val_iou:.4f}")

            # Salvar checkpoint a cada 10 épocas
            if (epoch + 1) % 10 == 0:
                checkpoint_path = os.path.join(checkpoint_dir, f"checkpoint_epoch_{epoch+1}.pth")
                save_checkpoint(self.model, optimizer, epoch, val_loss, checkpoint_path)

        total_time = time.time() - start_time
        print(f"\n🎉 Treinamento concluído em {total_time/60:.2f} minutos!")
        print(f"🏆 Melhor IoU de validação: {best_val_iou:.4f}")

        return best_val_iou

