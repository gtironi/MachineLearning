# Função para criar modelo com parâmetros específicos
def create_model(base_channels=32, depth=3, num_classes=32, padding_encoder=1, padding_decoder=1):
    """Cria modelo U-Net com parâmetros específicos"""
    if padding_encoder != 1 or padding_decoder != 1:
        # Criar versão modificada da UNet com padding customizado
        class CustomUNet(UNet):
            def __init__(self, n_channels=3, n_classes=32, depth=4, base_channels=64,
                        padding_encoder=1, padding_decoder=1, bilinear=False):
                super().__init__(n_channels, n_classes, depth, base_channels, bilinear)

                # Recriar encoder com padding customizado
                self.inc = DoubleConv(n_channels, base_channels, padding=padding_encoder)

                self.downs = nn.ModuleList()
                in_ch = base_channels
                for i in range(depth):
                    out_ch = base_channels * (2 ** (i + 1))
                    down_block = nn.Sequential(
                        nn.MaxPool2d(2),
                        DoubleConv(in_ch, out_ch, padding=padding_encoder)
                    )
                    self.downs.append(down_block)
                    in_ch = out_ch

                # Recriar decoder com padding customizado
                self.ups = nn.ModuleList()
                for i in range(depth):
                    skip_ch = base_channels * (2 ** (depth - i - 1))
                    if i == 0:
                        up_ch = base_channels * (2 ** depth)
                    else:
                        up_ch = out_ch

                    out_ch = skip_ch
                    up_block = Up(up_ch, skip_ch, out_ch, bilinear=True, padding=padding_decoder)
                    self.ups.append(up_block)

        # Modificar a classe Up para aceitar padding customizado
        class CustomUp(Up):
            def __init__(self, in_channels, skip_channels, out_channels, bilinear=False, padding=1):
                super().__init__(in_channels, skip_channels, out_channels, bilinear)
                if bilinear:
                    self.conv = DoubleConv(in_channels + skip_channels, out_channels, padding=padding)
                else:
                    self.conv = DoubleConv((in_channels // 2) + skip_channels, out_channels, padding=padding)

        # Usar CustomUNet se padding diferente
        model = CustomUNet(n_channels=3, n_classes=num_classes, depth=depth,
                          base_channels=base_channels, padding_encoder=padding_encoder,
                          padding_decoder=padding_decoder)
    else:
        model = UNet(n_channels=3, n_classes=num_classes, depth=depth, base_channels=base_channels)

    return model.to(device)

