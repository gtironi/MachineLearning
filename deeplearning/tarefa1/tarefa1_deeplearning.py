class SegmentationDataset(Dataset):
    def __init__(self, images_dir, masks_dir, transform=None, target_transform=None, in_memory = False):
        self.in_memory = in_memory
        self.images_dir = images_dir
        self.masks_dir = masks_dir
        self.transform = transform
        self.target_transform = target_transform
        self.images = []
        self.masks = []
        self.images_files = os.listdir(images_dir) #Posso usar aqui para controlar o tamanho do dataset (os.listdir(images_dir)[0:30])

        # Pré-carregamento na CPU para maior velociade
        if in_memory:
            for img_name in self.images_files:
                img_path = os.path.join(images_dir, img_name)
                mask_path = os.path.join(masks_dir, img_name.replace('.png', '_L.png'))

                # Read
                image = read_image(img_path).float() / 255.0  # já normalizado
                mask = read_image(mask_path)

                # Save in RAM memory
                self.images.append(image)
                self.masks.append(mask)

            #print("All images in Memory")

        self.rgb_values = torch.tensor(class_dict[['r', 'g', 'b']].values, dtype=torch.uint8).to(device)

    # Retorna o tamanho do dataset
    def __len__(self):
            return len(self.images_files)

    # Retorna uma imagem e uma label, dado um index
    def __getitem__(self, idx):
        if self.in_memory:
            image = self.images[idx].to(device) # Move image to GPU
            mask = self.masks[idx].to(device)
        else:
            img_name = self.images_files[idx]
            img_path = os.path.join(self.images_dir, img_name)
            mask_path = os.path.join(self.masks_dir, img_name.replace('.png', '_L.png'))

            # Load the image and mask
            image = read_image(img_path).to(device)  # Read and move image to GPU
            mask = read_image(mask_path).to(device)

        if self.transform:
            image = self.transform(image)
        if self.target_transform:
            mask = self.target_transform(mask)

        mask = self.mask_to_label(mask.permute(1,2,0))

        return image / 255 , mask

    def mask_to_label(self, img):
        # Get the width, height of the image (assuming img has shape [H, W, 3])
        h, w, _ = img.shape
        # Create an empty tensor
        labels = torch.zeros(h, w, device=device, dtype=torch.long)

        # Iterate over each class and map the pixels
        for i, color in enumerate(self.rgb_values):
            match = torch.all(torch.abs((img - color)) == 0, axis = -1)
            labels[match] = i

        return labels

