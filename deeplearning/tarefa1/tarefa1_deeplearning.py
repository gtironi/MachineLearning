class DoubleConv(nn.Module):
    """Double Convolution block used in U-Net"""
    def __init__(self, in_channels, out_channels, padding = 1, stride = 1): #esse padding e stride mantem o tamanho da imagem para kernel 3x3
        super(DoubleConv, self).__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, kernel_size = 3, padding=padding, stride = padding), # mudar o padding para diminuir a imagem (padding = 0 diminui 2 a cada convolução)
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, kernel_size = 3, padding=padding, stride = padding),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.conv(x)

class Down(nn.Module):
    """Downsampling block"""
    def __init__(self, in_channels, out_channels):
        super(Down, self).__init__()
        self.maxpool_conv = nn.Sequential(
            nn.MaxPool2d(2),
            DoubleConv(in_channels, out_channels) #alterar padding e stride se quiser (padding = 0)
        )

    def forward(self, x):
        return self.maxpool_conv(x)

class Up(nn.Module):
    def __init__(self, in_channels, skip_channels, out_channels, bilinear=False):
        super(Up, self).__init__()
        self.bilinear = bilinear
        if bilinear:
            self.up = nn.Upsample(scale_factor=2, mode='bilinear', align_corners=True)
            self.conv = DoubleConv(in_channels + skip_channels, out_channels)
        else:
            self.up = nn.ConvTranspose2d(in_channels, in_channels // 2, kernel_size=2, stride=2) #upsampling - por isso kernel 2
            self.conv = DoubleConv((in_channels // 2) + skip_channels, out_channels) #alterar padding e stride se quiser (padding = 2)

    def forward(self, x1, x2):
        x1 = self.up(x1)
        x1 = F.interpolate(x1, size=x2.shape[2:], mode='bilinear', align_corners=True)
        x = torch.cat([x2, x1], dim=1)
        return self.conv(x)


class UNet(nn.Module):
    """U-Net implementation with configurable depth"""
    def __init__(self, n_channels=3, n_classes=32, depth=4, base_channels=64, bilinear=False):
        super(UNet, self).__init__()
        self.n_channels = n_channels
        self.n_classes = n_classes
        self.depth = depth
        self.bilinear = bilinear

        #--------------------- Model -----------------------

        # Initial convolution
        self.inc = DoubleConv(n_channels, base_channels)

        # Encoder (downsampling path)
        self.downs = nn.ModuleList()
        in_ch = base_channels
        for i in range(depth):
            out_ch = base_channels * (2 ** (i + 1))
            self.downs.append(Down(in_ch, out_ch))
            in_ch = out_ch

        # Decoder (upsampling path)
        self.ups = nn.ModuleList()
        for i in range(depth):
            skip_ch = base_channels * (2 ** (depth - i - 1))
            if i == 0:
                up_ch = base_channels * (2 ** depth)
            else:
                up_ch = out_ch

            out_ch = skip_ch
            self.ups.append(Up(up_ch, skip_ch, out_ch, bilinear=True))

        # Final classification layer
        self.outc = nn.Conv2d(base_channels, n_classes, kernel_size=1)

        #--------------------- Model -----------------------

        # Calculate number of parameters
        self.num_params = sum(p.numel() for p in self.parameters())

    def forward(self, x):
        # Initial convolution
        x1 = self.inc(x)

        # Store skip connections
        skip_connections = [x1]

        # Encoder path
        x = x1
        for down in self.downs:
            x = down(x)
            skip_connections.append(x)

        # Decoder path
        for i, up in enumerate(self.ups):
            if i == 0:
                # First upsampling (from bottleneck)
                x = up(x, skip_connections[-(i + 2)])
            else:
                x = up(x, skip_connections[-(i + 2)])

        # Final classification
        logits = self.outc(x)
        return logits

    def get_num_parameters(self):
        return self.num_params

